"""Допуск на словоформы при поиске ключевых слов, AGENTS.md раздел 16 п.13.

Точное совпадение подстроки (было в `parser/classifier.py` изначально) пропускает
падежные/числовые формы русских слов — подтверждено вживую 2026-08-20 на реальных
публикациях sfr.gov.ru: «компенсацию» не матчилось на «компенсация», «мер поддержки»
(родительный падеж мн.ч.) — на «мера поддержки». Из 4 «похожих по теме» публикаций
одного источника 3 оказались пропущены именно поэтому.

Подход: для каждого слова ключевой фразы обрезаем типичное падежное окончание
(эвристика по длине слова, не морфологический анализ) и ищем результат как префикс
следующего слова в тексте — слова фразы должны идти **подряд**, в том же порядке. Это
осознанно отличается от эвристики, отклонённой при слиянии ветки `phase4-classifier`
(см. AGENTS.md раздел 16, там же): та требовала совпадения «стемов» слов НЕЗАВИСИМО
друг от друга в любом месте текста, что давало ложные срабатывания (пример из
AGENTS.md: «ветеран» → стем «ветер», совпадающий с обычным словом «ветер» = погода).
Здесь смежность слов сохраняется, а перед каждым стемом — граница слова (`\\b`), так
что подстрока не матчится посреди другого слова.

Поскольку `\\w*` после стема допускает и пустой хвост, точная исходная форма слова
всегда продолжает матчиться — это строгое расширение прежнего поведения, не замена.
"""
from __future__ import annotations

import functools
import re


def _word_stem(word: str) -> str:
    """Эвристика длины: длиннее 5 букв — обрезать 2 (частые окончания -ия/-ию/-ий/
    -ые/-ого и т.п.), 4-5 букв — обрезать 1, короче — не трогать (риск слишком общего
    стема выше пользы)."""
    if len(word) > 5:
        return word[:-2]
    if len(word) > 3:
        return word[:-1]
    return word


@functools.cache
def keyword_pattern(keyword: str) -> re.Pattern[str]:
    words = keyword.lower().split()
    parts = [r"\b" + re.escape(_word_stem(w)) + r"\w*" for w in words]
    return re.compile(r"\s+".join(parts))


def contains_keyword(text_lower: str, keywords: tuple[str, ...]) -> bool:
    return any(keyword_pattern(kw).search(text_lower) for kw in keywords)
