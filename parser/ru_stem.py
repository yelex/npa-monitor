"""Допуск на словоформы при поиске ключевых слов, AGENTS.md раздел 16 п.13.

Точное совпадение подстроки (было в `parser/classifier.py` изначально) пропускает
падежные/числовые формы русских слов — подтверждено вживую 2026-08-20 на реальных
публикациях sfr.gov.ru: «компенсацию» не матчилось на «компенсация», «мер поддержки»
(родительный падеж мн.ч.) — на «мера поддержки». Из 4 «похожих по теме» публикаций
одного источника 3 оказались пропущены именно поэтому.

Подход: для каждого слова ключевой фразы обрезаем типичное падежное окончание
(эвристика по длине слова, не морфологический анализ) и ищем результат как префикс
следующего слова в тексте — слова фразы должны идти **подряд**, в том же порядке. Это
осознанно отличается от эвристики, отклонённой при слиянии ветки `phase4-classifier`
(см. AGENTS.md раздел 16, там же): та требовала совпадения «стемов» слов НЕЗАВИСИМО
друг от друга в любом месте текста, что давало ложные срабатывания (пример из
AGENTS.md: «ветеран» → стем «ветер», совпадающий с обычным словом «ветер» = погода).
Здесь смежность слов сохраняется, а перед каждым стемом — граница слова (`\\b`), так
что подстрока не матчится посреди другого слова.

Поскольку `\\w*` после стема допускает и пустой хвост, точная исходная форма слова
всегда продолжает матчиться — это строгое расширение прежнего поведения, не замена.

**Найденное вживую исключение:** «доброволец» (ЖС «участник СВО») после обрезки даёт
стем «добровол», который матчится на «добровольно»/«добровольный» — частое слово в
совершенно не связанном по смыслу контексте («добровольное страхование» и т.п.), не
про СВО. Причина — беглая гласная в русском склонении: «доброволец» → «добровольца»
(родительный) теряет «е» перед «ц», и на этом же месте у прилагательного «доброво́льный»
стоит «ь» — то есть падежные формы существительного и прилагательного от общего корня
неразличимы префиксным обрезанием ни при какой длине стема. Такие слова — в
`_EXACT_WORD_OVERRIDES`: сопоставляются целым словом (без `\\w*`-хвоста), без учёта
словоформ — осознанная потеря полноты ради точности.

**Найденное вживую 2026-08-20 исключение того же класса:** «отмена» (маркер типа
события `repeal`) при стандартной обрезке (> 5 букв → минус 2) даёт стем «отме»,
который матчится на «отметил»/«отметила»/«отмечал» — частые, никак не связанные по
смыслу слова («отметил», «подчеркнул» = «noted», не «отменил»). Обнаружено на реальных
публикациях, найденных через Yandex Search (раздел 16 п.14 AGENTS.md): фразы вида «...
Иванов отметил необходимость...» ошибочно давали тип события «Отмена». В отличие от
«доброволец», здесь не нужен полный отказ от словоформ — «отмена»/«отменена»/
«отменён»/«отменено»/«отменили» и т.п. все совпадают уже по 5-буквенному стему «отмен»
(отличается от «отметил» на 5-й букве: «н» против «т»); обрезка именно на 2 буквы (а не
на 1, как для остальных слов той же длины) была слишком агрессивной для этого
конкретного слова. Такие слова — в `_STEM_LENGTH_OVERRIDES`: обрезаются на 1 букву
вместо стандартных 2, без полного отказа от словоформ.

**Найденное вживую 2026-08-24 исключение противоположного класса** (PLAN.md Фаза 9
п.5, `docs/SPEC_priority_substance_markers.md`): «новый» (`priority_high_words`,
AGENTS.md раздел 7) при стандартной обрезке (5 букв → минус 1) даёт стем «новы», не
матчащийся на «новую»/«новое»/«новых» и другие падежные/родовые формы — 4-я буква
после общего корня «нов» у этих форм разная (`ы` в именительном, `у` в винительном и
т.д.), это не хвост-окончание, а часть словоизменения. На реальном примере из дампа
пилота («…ввели новую меру поддержки…») слово `новый` из-за этого не матчилось вовсе.
Здесь, в отличие от «отмена», обрезка должна быть **агрессивнее** стандартной — 2
буквы вместо 1 — чтобы дойти до инвариантного 3-буквенного корня «нов», общего для
всех форм (новый/новая/новое/новые/нового/новую/новых/новым…). Коллизий с несвязанным
по смыслу словом не найдено — не считать «новость»/«новшество» ложным срабатыванием:
они однокоренные и по смыслу связаны с «новизной».

**Найдено систематическим аудитом 2026-08-24** (PLAN.md Фаза 9 п.6,
`docs/SPEC_classifier_false_positives.md`) — в отличие от предыдущих находок, **не**
подтверждено на исходном тексте конкретных ложных сигналов пилота (текст RSS-публикаций
[33]/[34] невосстановим — фид уже прокрутился, страница отдаёт CAPTCHA даже через
прокси, снепшота в архиве нет), только воспроизведено на синтетических примерах той же
тематики (рыбная отрасль, экономика Китая) — тот же класс риска, что и «доброволец»/
«отмена», найден проактивным прогоном всех односложных ключевых слов справочника через
эту эвристику:

- «инвалид» (ЖС «Люди с инвалидностью») при стандартной обрезке (7 букв → минус 2) даёт
  стем «инвал», который матчится на «инвалюта»/«инвалютный» — финансовый термин
  («инвалютные резервы»), никак не связанный с инвалидностью. Обрезка на 1 букву вместо
  2 → стем «инвали» (6 букв, расходится с «инвалюта» уже на этой букве: `и` против `ю`)
  — сохраняет все падежные формы, включая «инвалидность».
- «контрактник» (ЖС «Участники СВО») при стандартной обрезке (11 букв → минус 2) даёт
  стем «контрактн», который матчится на прилагательное «контрактный»/«контрактная» (в
  юридическом/закупочном смысле — «на контрактной основе», обычная лексика госзакупок и
  распределения квот, не про контрактников-военнослужащих). Обрезка на 1 букву вместо 2
  → стем «контрактни» (10 букв, расходится с «контрактный» на этой букве: `и` против
  `ы`/`о`/`а`) — сохраняет все падежные формы существительного.
- «выплата» (тематический блок 5.2) при стандартной обрезке (7 букв → минус 2) даёт
  стем «выпла», который матчится на «выплакать»/«выплакала» (плакать, излить горе) —
  редкое, но никак не связанное по смыслу слово. Обрезка на 1 букву вместо 2 → стем
  «выплат» (6 букв, расходится с «выплакать» на этой букве: `т` против `к`) — сохраняет
  все падежные формы («выплаты»/«выплате»/«выплату»/«выплатой»/«выплатам»/…).

Третья похожая находка того же аудита — «закон» (`document_markers`) матчится на
«закончить»/«закончился» — **сознательно не исправлена**: коллизия не в обрезке стема
(само слово «закон» уже литеральная подстрока «закончить»), любой фикс либо ничего не
меняет, либо требует `_EXACT_WORD_OVERRIDES` ценой потери важных падежных форм
(«закона»/«законодательство»). Влияет только на приоритизацию (раздел 7 AGENTS.md), не
на релевантность — задокументированный остаточный риск, не устранён.
"""
from __future__ import annotations

import functools
import re

# Слова, для которых обрезка окончания создаёт коллизию с частым, но не связанным по
# смыслу однокоренным словом (см. докстринг модуля) — сопоставляются только точно.
_EXACT_WORD_OVERRIDES = frozenset({"доброволец"})

# Слова, для которых стандартная длина обрезки (по _word_stem) даёт неверный стем —
# либо слишком общий (коллизия с несвязанным словом: "отмена", "инвалид",
# "контрактник", "выплата"), либо слишком узкий (не покрывает реальные словоформы,
# "новый") — см. докстринг модуля.
_STEM_LENGTH_OVERRIDES: dict[str, int] = {
    "отмена": 1,
    "новый": 2,
    "инвалид": 1,
    "контрактник": 1,
    "выплата": 1,
}


def _word_pattern_part(word: str) -> str:
    if word in _EXACT_WORD_OVERRIDES:
        return r"\b" + re.escape(word) + r"\b"
    return r"\b" + re.escape(_word_stem(word)) + r"\w*"


def _word_stem(word: str) -> str:
    """Эвристика длины: длиннее 5 букв — обрезать 2 (частые окончания -ия/-ию/-ий/
    -ые/-ого и т.п.), 4-5 букв — обрезать 1, короче — не трогать (риск слишком общего
    стема выше пользы). `_STEM_LENGTH_OVERRIDES` — точечное исключение из этой длины
    для конкретных слов, где стандартная обрезка даёт коллизию (см. докстринг модуля)."""
    if word in _STEM_LENGTH_OVERRIDES:
        cut = _STEM_LENGTH_OVERRIDES[word]
        return word[:-cut] if cut else word
    if len(word) > 5:
        return word[:-2]
    if len(word) > 3:
        return word[:-1]
    return word


@functools.cache
def keyword_pattern(keyword: str) -> re.Pattern[str]:
    words = keyword.lower().split()
    parts = [_word_pattern_part(w) for w in words]
    return re.compile(r"\s+".join(parts))


def contains_keyword(text_lower: str, keywords: tuple[str, ...]) -> bool:
    return any(keyword_pattern(kw).search(text_lower) for kw in keywords)


def find_matches(text_lower: str, keywords: tuple[str, ...]) -> tuple[str, ...]:
    """Как `contains_keyword`, но возвращает сами совпавшие ключевые слова — для
    трейса классификации (PLAN.md Фаза 6+, «видеть, как парсер принимает решение»)."""
    return tuple(kw for kw in keywords if keyword_pattern(kw).search(text_lower))
